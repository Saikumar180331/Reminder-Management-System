
import { useState } from "react";
import { useNavigate } from "react-router-dom";

import {
  ArrowLeft,
  UserPlus,
  Save,
  X
} from "lucide-react";

import "../../styles/employees.css";

const API_URL = "http://127.0.0.1:5000/api/employees";

function AddEmployee() {
  const navigate = useNavigate();

  const [employee, setEmployee] = useState({
    name: "",
    email: "",
    phone: ""
  });

  const [errors, setErrors] = useState({});
  const [formError, setFormError] = useState("");
  const [saving, setSaving] = useState(false);

  // Normalize phone
  const normalizePhone = (phone) =>
    phone.trim().replace(/\s+/g, "");

  // Handle input changes
  const handleChange = (e) => {
    const { name, value } = e.target;

    setEmployee((previous) => ({
      ...previous,
      [name]: value
    }));

    setErrors((previous) => ({
      ...previous,
      [name]: ""
    }));

    setFormError("");
  };

  // Validate form
  const validate = () => {
    const newErrors = {};

    if (!employee.name.trim()) {
      newErrors.name = "Employee name is required.";
    }

    if (!employee.email.trim()) {
      newErrors.email = "Email address is required.";
    } else if (
      !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(employee.email.trim())
    ) {
      newErrors.email = "Enter a valid email address.";
    }

    if (!employee.phone.trim()) {
      newErrors.phone = "Phone number is required.";
    } else if (
      !/^\+1\s\(\d{3}\)\s\d{3}-\d{4}$/.test(employee.phone.trim())
    ) {
      newErrors.phone = "Use format: +1 (212) 555-0123";
    }

    return newErrors;
  };

  // Save employee to Flask and MySQL
  const handleSubmit = async (e) => {
    e.preventDefault();

    const newErrors = validate();

    setErrors(newErrors);
    setFormError("");

    if (Object.keys(newErrors).length > 0) {
      return;
    }

    try {
      setSaving(true);

      const response = await fetch(API_URL, {
        method: "POST",

        headers: {
          "Content-Type": "application/json"
        },

        credentials: "include",

        body: JSON.stringify({
          name: employee.name.trim(),
          email: employee.email.trim().toLowerCase(),
          phone: normalizePhone(employee.phone)
        })
      });

      const data = await response.json();

      if (!response.ok) {
        if (response.status === 409) {
          const message = data.message || "Duplicate employee details.";

          if (message.toLowerCase().includes("email")) {
            setErrors({
              email: message
            });
          } else if (message.toLowerCase().includes("phone")) {
            setErrors({
              phone: message
            });
          } else {
            setFormError(message);
          }

          return;
        }

        throw new Error(
          data.message || "Unable to add employee."
        );
      }

      alert(data.message || "Employee added successfully!");

      navigate("/employees");

    } catch (error) {
      console.error("ADD EMPLOYEE ERROR:", error);

      setFormError(
        "Unable to connect to the Flask server. Check whether the backend is running."
      );

    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="add-employee-page">
      <div className="employees-container">

        {/* Header */}
        <div className="add-employee-header">

          <div className="add-employee-title">

            <div className="add-title-icon">
              <UserPlus size={26} />
            </div>

            <h2>Add New Employee</h2>

            <p>
              Register a new employee by entering their details below.
            </p>

          </div>

          <button
            type="button"
            className="back-btn"
            onClick={() => navigate("/employees")}
          >
            <ArrowLeft size={17} />
            Back
          </button>

        </div>

        {/* Form */}
        <form
          className="employee-form"
          onSubmit={handleSubmit}
          noValidate
        >

          <div className="form-section-heading">
            <h3>Personal Information</h3>

            <p>
              Provide the employee's basic contact information.
            </p>
          </div>

          {/* Employee ID */}
          <div className="form-group">
            <label>Employee ID</label>

            <input
              type="text"
              value="Automatically generated by database"
              disabled
            />

            <small className="field-hint">
              The database generates a unique employee ID after saving.
            </small>
          </div>

          {/* Name */}
          <div className="form-group">
            <label>Employee Name</label>

            <input
              type="text"
              name="name"
              value={employee.name}
              onChange={handleChange}
              placeholder="Enter employee full name"
            />

            {errors.name && (
              <span className="error-text">
                {errors.name}
              </span>
            )}
          </div>

          {/* Email */}
          <div className="form-group">
            <label>Email Address</label>

            <input
              type="email"
              name="email"
              value={employee.email}
              onChange={handleChange}
              placeholder="example@gmail.com"
            />

            {errors.email && (
              <span className="error-text">
                {errors.email}
              </span>
            )}
          </div>

          {/* Phone */}
          <div className="form-group">
            <label>Phone Number</label>

            <input
              type="tel"
              name="phone"
              value={employee.phone}
              onChange={handleChange}
              placeholder="+1 (212) 555-0123"
            />

            {errors.phone && (
              <span className="error-text">
                {errors.phone}
              </span>
            )}
          </div>

          {/* API Error */}
          {formError && (
            <div className="error-message">
              {formError}
            </div>
          )}

          {/* Buttons */}
          <div className="form-actions">

            <button
              type="button"
              className="secondary-btn"
              onClick={() => navigate("/employees")}
              disabled={saving}
            >
              <X size={17} />
              Cancel
            </button>

            <button
              type="submit"
              className="primary-btn"
              disabled={saving}
            >
              <Save size={17} />
              {saving ? "Saving..." : "Save Employee"}
            </button>

          </div>

        </form>
      </div>
    </div>
  );
}

export default AddEmployee;
